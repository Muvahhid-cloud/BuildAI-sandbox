#!/usr/bin/env node
// Generates TypeScript types from the Pydantic-exported JSON Schemas.
// Input:  generated/*.schema.json   (written by `pnpm schema` from the API)
// Output: src/generated/*.ts
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const targets = [
  { schema: "building-model.schema.json", out: "building-model.ts", name: "BuildingModel" },
  {
    schema: "building-specification.schema.json",
    out: "building-specification.ts",
    name: "BuildingSpecification",
  },
  { schema: "ai-generation.schema.json", out: "ai-generation.ts", name: "AIGenerationContracts" },
];

for (const target of targets) {
  const schema = JSON.parse(await readFile(join(root, "generated", target.schema), "utf8"));
  const ts = await compile(schema, target.name, {
    bannerComment:
      `/* GENERATED by packages/schema/scripts/generate.mjs from the Pydantic ${target.name}.\n` +
      " * Do not edit by hand - run `pnpm schema` from the repo root. */",
    additionalProperties: false,
    ignoreMinAndMaxItems: true,
    unreachableDefinitions: true,
    format: true,
    style: { printWidth: 100, trailingComma: "all" },
  });
  const outPath = join(root, "src", "generated", target.out);
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, ts.replace(/\r\n/g, "\n"), "utf8");
  console.log(`wrote ${outPath}`);
}
